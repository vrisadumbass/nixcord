    /// A still for the video player (`crate::video`): `url` decoded into a `px` box. Paints
    /// nothing and opens no viewer. `Ok(None)` while loading, `Err` if it failed (or in demo
    /// mode, which has no network).
    #[cfg_attr(not(feature = "video"), allow(dead_code))]
    pub fn still(&mut self, url: &str, px: (u32, u32)) -> Result<Option<Tex>, ()> {
        if self.demo {
            return Err(());
        }
        match self.net(Key::new(url, px.0, px.1)) {
            Got::Ready(t) => Ok(Some(t)),
            Got::Loading => Ok(None),
            Got::Failed => Err(()),
        }
    }

    /// A small decorative image (embed author icon, nameplate, tag badge) decoded into a
    /// `px` box, for the caller to paint. `None` while loading or if it failed. In demo
    /// mode it comes from `assets/demo` when the URL is mapped there, else it is generated.
    pub fn texture(&mut self, url: &str, px: (u32, u32)) -> Option<Tex> {
        self.begin_pass();
        let got = if self.demo {
            let seed = murl::fnv1a64(url.as_bytes());
            let file = self.demo_url_file(url);
            self.local_file(local_id(4, seed, px.0, px.1), file, px, move || {
                demo::screenshot(seed, px.0, px.1)
            })
        } else {
            self.net(Key::new(url, px.0, px.1))
        };
        match got {
            Got::Ready(t) => Some(t),
            _ => None,
        }
    }

    fn image_with(
        &mut self,
        ui: &mut Ui,
        url: &str,
        alt: &[String],
        max_size: Vec2,
        natural: Option<(u32, u32)>,
        interactive: bool,
    ) -> Option<Response> {
        self.begin_pass();
        let ppp = self.ctx.pixels_per_point();
        let max = (max_size.x.max(1.0), max_size.y.max(1.0));
        // Size we lay out at; with no natural size, a 16:9 box until the image arrives.
        let fallback = (max.0, max.0 * 9.0 / 16.0);
        let (w, h) = size::fit_points(
            natural
                .map(|(w, h)| (w as f32, h as f32))
                .unwrap_or(fallback),
            max,
        );
        let (pw, ph) = (size::to_px(w, ppp), size::to_px(h, ppp));
        let seed = murl::fnv1a64(url.as_bytes());
        let key = if self.demo {
            None
        } else if natural.is_some() {
            Some(Key::new(murl::sized_url(url, pw, ph), pw, ph))
        } else {
            // Unknown size: decode into the whole max box, then lay out by its aspect.
            let (mw, mh) = (size::to_px(max.0, ppp), size::to_px(max.1, ppp));
            Some(Key::new(url, mw, mh))
        };
        let preview_id = key
            .as_ref()
            .map_or_else(|| local_id(4, seed, pw, ph), Key::id);
        // Animated: decode every frame (attachments / gifv / animated WebP).
        let anim_urls = if !alt.is_empty() {
            Some(alt.to_vec())
        } else if nixcord_media::anim_url::maybe_animated(url) {
            Some(match natural {
                Some(_) => nixcord_media::anim_url::image_candidates(url, pw, ph),
                None => vec![url.to_owned()],
            })
        } else {
            None
        };
        let anim_px = key.as_ref().map_or((pw, ph), |k| (k.max_w, k.max_h));
        let anim_id = match alt.first() {
            Some(a) => local_id(8, murl::fnv1a64(a.as_bytes()), anim_px.0, anim_px.1),
            None => preview_id,
        };

        // Visible check needs a rect, but the rect for unknown sizes depends on the texture:
        // peek at the would-be rect first.
        let probe = Rect::from_min_size(ui.cursor().min, Vec2::new(w, h));
        let mut badge = false;
        let got = if !ui.is_rect_visible(probe) {
            Got::Loading
        } else if let Some(urls) = &anim_urls {
            let shown = self.anim_get(anim::Req {
                id: anim_id,
                urls,
                px: anim_px,
                // Same seed as the viewer uses (it keys on the animated URL).
                demo: Some(match alt.first() {
                    Some(a) => {
                        anim::DemoAnim::Party(murl::fnv1a64(a.as_bytes()), self.demo_url_file(a))
                    }
                    None => anim::DemoAnim::Party(seed, self.demo_url_file(url)),
                }),
                hover: ui.rect_contains_pointer(probe),
                viewer: false,
            });
            badge = shown.badge;
            match (shown.got, key) {
                // gifv: the poster still while the animation loads (or if it can't).
                (Got::Loading | Got::Failed, Some(key)) if !alt.is_empty() => self.net(key),
                (g, _) => g,
            }
        } else if let Some(key) = key {
            self.net(key)
        } else {
            let file = self.demo_url_file(url);
            self.local_file(preview_id, file, (pw, ph), move || {
                demo::screenshot(seed, pw, ph)
            })
        };
        let shown = match (&got, natural) {
            (Got::Ready(t), None) => {
                let (tw, th) =
                    size::fit_points((t.size[0] as f32 / ppp, t.size[1] as f32 / ppp), max);
                Vec2::new(tw, th)
            }
            _ => Vec2::new(w, h),
        };
        let (rect, resp) = if interactive {
            let (rect, resp) = ui.allocate_exact_size(shown, Sense::click());
            (rect, Some(resp))
        } else {
            let (_, rect) = ui.allocate_space(shown);
            (rect, None)
        };
        let rounding = CornerRadius::same(IMAGE_RADIUS);
        let v = ui.visuals();
        match got {
            Got::Ready(t) => {
                paint_texture(ui, rect, rounding, t, false);
                if badge {
                    anim::paint_badge(ui, rect);
                }
            }
            Got::Loading => {
                ui.painter().rect_filled(rect, rounding, v.faint_bg_color);
            }
            Got::Failed => {
                ui.painter().rect_filled(rect, rounding, v.faint_bg_color);
                ui.painter().text(
                    rect.center(),
                    Align2::CENTER_CENTER,
                    "Image unavailable",
                    crate::ui::prop(12.0),
                    v.weak_text_color(),
                );
            }
        }

        let resp = resp?;
        let group = gallery_group(ui.stack());
        let img = ViewImage {
            url: url.to_owned(),
            natural,
            filename: murl::file_name(url),
            preview_id,
            alt: Vec::new(),
        };
        let img = match alt.first() {
            Some(a) => ViewImage {
                url: a.clone(),
                filename: murl::file_name(a),
                preview_id: anim_id,
                alt: alt.to_vec(),
                ..img
            },
            None => img,
        };
        if resp.clicked() {
            self.open = Some((group, img.clone()));
        }
        self.drawn.push((group, img));
        Some(resp.on_hover_cursor(egui::CursorIcon::PointingHand))
    }

