//! Images in the UI: avatars, server icons, custom emoji, attachment/embed previews.
//!
//! # Usage (for the UI integration pass)
//!
//! Own one `Media` in `NixApp` (`media: Media::new(&cc.egui_ctx, demo)`), pass `&mut app.media`
//! down to the screens. Nothing else is needed: the first helper call of each frame drains
//! finished downloads into textures and evicts least-recently-used textures over the byte
//! cap. Requests are fire-and-forget; when an image arrives the UI is repainted. Every
//! helper draws a fallback while loading / on failure, and only requests images whose rect
//! is visible (`ui.is_rect_visible`), so off-screen rows of the chat list cost nothing.
//!
//! - `media.avatar(ui, &user, guild, 40.0)` allocates a 40x40 circle and returns its
//!   `Response`. `guild` is `Some((guild_id, member.avatar.as_deref()))` for guild messages
//!   (a per-guild avatar wins over the global one) or `None` for DMs. Users without an avatar
//!   hash keep the colored initials circle (`ui::paint_avatar`); no default-avatar fetch.
//!   - `media.paint_avatar(ui, center, 40.0, &user, guild)` is the drop-in replacement for
//!     `ui::paint_avatar(ui, center, 40.0, &user)` when the rect is already allocated.
//! - `media.paint_guild_icon(ui, rect, &guild, rounding) -> bool` paints the server icon into
//!   an allocated rect with the given rounding (the rail passes its animated circle ->
//!   squircle radius). It draws NO fallback and returns `false` when there is no image
//!   (yet), so the rail keeps painting its own hover/selected fill + initials.
//! - `media.emoji(ui, emoji_id, animated, 22.0)` for custom emoji (reactions, inline
//!   `<:name:id>`). Animated emoji play (see `media/anim.rs`); the still shows while the
//!   frames load. Fallback: a faint rounded square.
//! - `media.image(ui, &url, Vec2::new(400.0, 300.0), Some((w, h)))` for attachments
//!   (`a.url`, `a.width.zip(a.height)`) and embed images/thumbnails (prefer `proxy_url`,
//!   `media.width.zip(media.height)`). Aspect-correct inside `max_size`, never upscaled,
//!   rounded corners; a click opens the in-app image viewer (`ui::viewer`), stepping through
//!   the other images of the same message (see "Viewer" below). Pass `natural` whenever
//!   known so the row height is stable before the image arrives (the chat list caches row
//!   heights). Discord attachment / embed-proxy URLs are fetched pre-scaled by the media
//!   proxy, so we download about as many pixels as we show.
//! - GIFs and animated WebP/APNG (attachments, `gifv` embeds via `media.gifv(..)`,
//!   animated emoji, `a_` avatars on hover) play inline; see `media/anim.rs` for the memory
//!   budget and playback rules. `media.video_poster(..)` draws a video's poster with a
//!   play button that opens the browser.
//! - `media.clear()` on logout drops every texture and closes the viewer;
//!   `media.stats()` -> `(textures, bytes)` of the LRU (viewer textures are not counted).
//!
//! # Viewer
//!
//! A click on an image stores an open request (URL, natural size, file name from the URL)
//! plus a "gallery" id: the chat list row (the item directly inside the `ScrollArea`) the
//! image was drawn in, read from egui's `UiStack`, so the chat code needs no change. The
//! viewer (`ui::viewer::show`, drawn last each frame) takes the request together with every
//! image drawn in the same row this pass.
//!
//! The viewer asks for a large copy sized to the window's pixel size (rounded up to 512 px
//! steps so resizing doesn't refetch every frame) or the natural size, whichever is smaller,
//! under its own `Key`, so the small preview stays cached and is drawn scaled up until the
//! large one arrives. Large textures live outside the LRU (one image can be 8-30 MB of
//! RGBA): only the current image's is kept, and `close_viewer` drops it at once. A late
//! download for a closed viewer is discarded instead of entering the LRU.
//!
//! `media.save(&img)` shows a native save dialog (rfd) on a helper thread, then streams the
//! original file to disk on the fetcher; `take_notices()` returns "saved" / error messages
//! for the toast.
//!
//! Demo mode (`Media::new(ctx, true)`) never touches the network: avatars, icons, emoji,
//! attachments and GIFs are read from `assets/demo` (see `crate::demo_assets`; decoded on a
//! helper thread), mapped from the fake avatar / icon hashes, emoji ids and URL file names.
//! Without that folder (an installed exe) they are generated by `nixcord_media::demo`,
//! seeded by the user/guild/emoji id or a hash of the URL.
//!
//! Users without an avatar hash get Discord's default-avatar look
//! (`ui::paint_default_avatar`) in both modes.
//!
//! # Unicode emoji (Twemoji)
//!
//! `media.twemoji(emoji, px)` returns the color Twemoji image of a unicode emoji decoded to
//! `px` pixels square (one cache entry per emoji and size, like any other image; the PNGs
//! are 72x72, so even the picker's 48 px cells cost 9 KB each). `None` while loading or
//! after a failure: callers draw the font glyph instead (see `ui::emoji_text`). In demo
//! mode Twemoji comes from the disk cache only (no network), unless `NIXCORD_DEMO_NET=1`
//! allows fetching it.

