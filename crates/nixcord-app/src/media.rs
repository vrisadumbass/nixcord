    /// Circle avatar of `size` points. See the module docs for `guild`.
    pub fn avatar(
        &mut self,
        ui: &mut Ui,
        user: &User,
        guild: Option<(Snowflake, Option<&str>)>,
        size: f32,
    ) -> Response {
        let (rect, resp) = ui.allocate_exact_size(Vec2::splat(size), Sense::click());
        self.paint_avatar(ui, rect.center(), size, user, guild);
        resp
    }

    /// Paint a circle avatar into an already allocated area (drop-in for `ui::paint_avatar`).
    pub fn paint_avatar(
        &mut self,
        ui: &Ui,
        center: Pos2,
        diameter: f32,
        user: &User,
        guild: Option<(Snowflake, Option<&str>)>,
    ) {
        let rect = Rect::from_center_size(center, Vec2::splat(diameter));
        let member = guild.and_then(|(g, h)| h.map(|h| (g, h)));
        let Some(hash) = member.map(|(_, h)| h).or(user.avatar.as_deref()) else {
            crate::ui::paint_default_avatar(ui, center, diameter, user.id);
            return;
        };
        if ui.is_rect_visible(rect) {
            let px = self.px(diameter);
            let got = if self.demo {
                let seed = user.id.0;
                self.local_file(
                    local_id(1, murl::fnv1a64(hash.as_bytes()) ^ seed, px, px),
                    demo_assets::avatar_file(hash),
                    (px, px),
                    move || demo::avatar(seed, px),
                )
            } else {
                let url = match (member, user.avatar.as_deref()) {
                    (Some((g, h)), _) => {
                        Some(cdn::member_avatar(g, user.id, h, size::cdn_size(px)))
                    }
                    (None, Some(h)) => Some(cdn::avatar(user.id, Some(h), size::cdn_size(px))),
                    (None, None) => None,
                };
                let hover_anim = hash.starts_with("a_") && ui.rect_contains_pointer(rect);
                match url {
                    Some(url) => match hover_anim.then(|| self.anim_avatar(&url, px)).flatten() {
                        Some(t) => Got::Ready(t),
                        None => self.net(Key::new(url, px, px)),
                    },
                    None => Got::Failed,
                }
            };
            if let Got::Ready(t) = got {
                paint_texture(ui, rect, radius(diameter / 2.0), t, true);
                return;
            }
        }
        crate::ui::paint_avatar(ui, center, diameter, user);
    }

    /// Paint the server icon into `rect`. Draws nothing and returns `false` if there is no
    /// icon or it is not loaded (yet), so the caller can draw its own fallback.
    pub fn paint_guild_icon(
        &mut self,
        ui: &Ui,
        rect: Rect,
        guild: &Guild,
        rounding: CornerRadius,
    ) -> bool {
        if !ui.is_rect_visible(rect) {
            return false;
        }
        let px = self.px(rect.width().max(rect.height()));
        let got = if self.demo {
            let Some(hash) = guild.icon.as_deref() else {
                return false;
            };
            let seed = guild.id.0;
            self.local_file(
                local_id(2, seed, px, px),
                demo_assets::icon_file(hash),
                (px, px),
                move || demo::guild_icon(seed, px),
            )
        } else {
            match guild.icon.as_deref() {
                Some(h) => self.net(Key::new(
                    cdn::guild_icon(guild.id, h, size::cdn_size(px)),
                    px,
                    px,
                )),
                None => Got::Failed,
            }
        };
        match got {
            Got::Ready(t) => {
                paint_texture(ui, rect, rounding, t, true);
                true
            }
            _ => false,
        }
    }

    /// Custom emoji in a `size` x `size` box (aspect kept, centered).
    pub fn emoji(&mut self, ui: &mut Ui, id: Snowflake, animated: bool, size: f32) -> Response {
        let (rect, resp) = ui.allocate_exact_size(Vec2::splat(size), Sense::hover());
        if ui.is_rect_visible(rect) {
            let px = self.px(size);
            let hover = ui.rect_contains_pointer(rect);
            let frame = animated.then(|| self.anim_emoji(id.0, px, hover)).flatten();
            let got = if let Some(t) = frame {
                Got::Ready(t)
            } else if self.demo {
                let seed = id.0;
                self.local_file(
                    local_id(3, seed, px, px),
                    demo_assets::emoji_file(seed),
                    (px, px),
                    move || demo::emoji(seed, px),
                )
            } else {
                self.net(Key::new(
                    cdn::emoji(id, animated, size::cdn_size(px)),
                    px,
                    px,
                ))
            };
            match got {
                Got::Ready(t) => {
                    // Contain: scale the texture (in pixels) to fit the box (in points).
                    let (tw, th) = (t.size[0].max(1) as f32, t.size[1].max(1) as f32);
                    let k = (rect.width() / tw).min(rect.height() / th);
                    let r = Rect::from_center_size(rect.center(), Vec2::new(tw * k, th * k));
                    paint_texture(ui, r, CornerRadius::ZERO, t, false);
                }
                _ => {
                    ui.painter().rect_filled(
                        rect.shrink(size * 0.08),
                        radius(size * 0.2),
                        ui.visuals().faint_bg_color,
                    );
                }
            }
        }
        resp
    }

    /// Lookup status for unicode emoji `emoji` at `px` pixels (starts the load on a miss).
    /// Distinguishes in-flight loads from offline/failed lookups.
    pub fn twemoji_status(&mut self, emoji: &str, px: u32) -> TwemojiStatus {
        let px = px.clamp(8, 160);
        let key = Key::new(nixcord_emoji::twemoji_url(emoji), px, px);
        self.begin_pass();
        let id = key.id();
        if let Some(g) = self.cached(id) {
            return match g {
                Got::Ready(t) => TwemojiStatus::Ready(t),
                Got::Loading => TwemojiStatus::Loading,
                Got::Failed => TwemojiStatus::Failed,
            };
        }
        if !self.ensure_emoji_fetcher() {
            self.entries.insert(
                id,
                Entry::Failed {
                    retry_at: Instant::now() + std::time::Duration::from_secs(3600),
                },
            );
            return TwemojiStatus::Failed;
        }
        if let Some(f) = &self.fetcher {
            f.request(key);
        }
        self.entries.insert(id, Entry::Loading);
        TwemojiStatus::Loading
    }

    /// [`Media::twemoji_status`] for an emoji drawn `size` points square.
    pub fn twemoji_points_status(&mut self, emoji: &str, size: f32) -> TwemojiStatus {
        let px = self.px(size);
        self.twemoji_status(emoji, px)
    }

    /// Color Twemoji texture of unicode emoji `emoji` at `px` pixels, if loaded (starts the
    /// load on a miss). See the module docs.
    pub fn twemoji(&mut self, emoji: &str, px: u32) -> Option<Tex> {
        match self.twemoji_status(emoji, px) {
            TwemojiStatus::Ready(t) => Some(t),
            _ => None,
        }
    }

    /// [`Media::twemoji`] for an emoji drawn `size` points square.
    pub fn twemoji_points(&mut self, emoji: &str, size: f32) -> Option<Tex> {
        let px = self.px(size);
        self.twemoji(emoji, px)
    }

    /// Texture of a custom emoji drawn `size` points square, if loaded (starts the load on a
    /// miss). Backs the markdown renderer's `EmojiImages` hook.
    pub fn emoji_texture(&mut self, id: u64, animated: bool, size: f32) -> Option<TextureId> {
        let px = self.px(size);
        let frame = animated.then(|| self.anim_emoji(id, px, false)).flatten();
        let got = if let Some(t) = frame {
            Got::Ready(t)
        } else if self.demo {
            self.local_file(
                local_id(3, id, px, px),
                demo_assets::emoji_file(id),
                (px, px),
                move || demo::emoji(id, px),
            )
        } else {
            self.net(Key::new(
                cdn::emoji(Snowflake(id), animated, size::cdn_size(px)),
                px,
                px,
            ))
        };
        match got {
            Got::Ready(t) => Some(t.id),
            _ => None,
        }
    }
